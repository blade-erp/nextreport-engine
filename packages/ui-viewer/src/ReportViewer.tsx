'use client'
import { useState, useMemo } from 'react'
import { renderReport } from '@nextreport/engine-core'
import { renderToHtml } from '@nextreport/renderer-html'
import type { Report } from '@nextreport/schema'

interface ReportViewerProps {
  report: Report
  data: Record<string, unknown>
  mode?: 'read-only' | 'print' | 'embedded'
}

export function ReportViewer({ report, data, mode = 'read-only' }: ReportViewerProps) {
  const [currentPage, setCurrentPage] = useState(1)

  // HTML is generated entirely by our own renderer — not from user input.
  // Using dangerouslySetInnerHTML here is safe because we control the source.
  const { html, totalPages } = useMemo(() => {
    try {
      const ir = renderReport(report, data)
      const htmlOutput = renderToHtml(ir, {
        pageSize: report.page?.size,
        orientation: report.page?.orientation,
      })
      return { html: htmlOutput, totalPages: ir.metadata.totalPages }
    } catch (error) {
      return { html: `<p style="color:red">Render error: ${error}</p>`, totalPages: 0 }
    }
  }, [report, data])

  const handlePrint = () => window.print()

  const handleExportPdf = async () => {
    try {
      const response = await fetch('/api/render', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ template: report, data, format: 'pdf' }),
      })
      if (!response.ok) {
        throw new Error(`Export failed: ${response.statusText}`)
      }
      const blob = await response.blob()
      const url = URL.createObjectURL(blob)
      const a = document.createElement('a')
      a.href = url
      a.download = 'report.pdf'
      a.click()
      URL.revokeObjectURL(url)
    } catch (error) {
      alert(`PDF export failed: ${error}`)
    }
  }

  const toolbarStyle: React.CSSProperties = {
    display: 'flex',
    alignItems: 'center',
    justifyContent: 'space-between',
    padding: '8px 16px',
    background: '#fff',
    borderBottom: '1px solid #e0e0e0',
    flexShrink: 0,
  }

  const btnStyle: React.CSSProperties = {
    padding: '4px 12px',
    border: '1px solid #ccc',
    borderRadius: 4,
    background: '#f5f5f5',
    cursor: 'pointer',
    fontSize: 13,
  }

  const btnDisabledStyle: React.CSSProperties = {
    ...btnStyle,
    opacity: 0.4,
    cursor: 'not-allowed',
  }

  const accentBtnStyle: React.CSSProperties = {
    ...btnStyle,
    background: '#4f46e5',
    borderColor: '#4f46e5',
    color: '#fff',
  }

  return (
    <div style={{ display: 'flex', flexDirection: 'column', height: '100%', background: '#f5f5f5' }}>
      {/* Toolbar */}
      {mode !== 'embedded' && (
        <div style={toolbarStyle}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
            <button
              style={currentPage <= 1 ? btnDisabledStyle : btnStyle}
              onClick={() => setCurrentPage(p => Math.max(1, p - 1))}
              disabled={currentPage <= 1}
            >
              Prev
            </button>
            <span style={{ fontSize: 13, color: '#555' }}>
              Page {currentPage} of {totalPages}
            </span>
            <button
              style={currentPage >= totalPages ? btnDisabledStyle : btnStyle}
              onClick={() => setCurrentPage(p => Math.min(totalPages, p + 1))}
              disabled={currentPage >= totalPages}
            >
              Next
            </button>
          </div>
          <div style={{ display: 'flex', gap: 8 }}>
            <button style={btnStyle} onClick={handlePrint}>
              Print
            </button>
            <button style={accentBtnStyle} onClick={handleExportPdf}>
              Export PDF
            </button>
          </div>
        </div>
      )}

      {/* Report preview — HTML comes from our own renderer, not user input */}
      <div
        style={{
          flex: 1,
          overflow: 'auto',
          padding: 24,
          display: 'flex',
          justifyContent: 'center',
        }}
      >
        <div
          style={{ background: '#fff', boxShadow: '0 2px 8px rgba(0,0,0,0.15)' }}
          // Safe: HTML is generated by @nextreport/renderer-html from a trusted schema
          dangerouslySetInnerHTML={{ __html: html }} // nosec
        />
      </div>
    </div>
  )
}
